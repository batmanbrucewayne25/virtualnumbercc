/**
 * @desc    Save reseller Razorpay configuration
 * @route   POST /api/razorpay/config
 * @access  Private (Reseller only)
 */
export const saveResellerConfig = asyncHandler(async (req, res) => {
  let { reseller_id, webhook_secret } = req.body;
  
  // FAANG-grade security: Ensure resellers can only save config for themselves
  if (req.user && req.user.role === 'reseller') {
    reseller_id = req.user.userId;
  }
  
  // Trim keys to prevent whitespace issues
  const key_id = req.body.key_id ? req.body.key_id.trim() : req.body.key_id;
  const key_secret = req.body.key_secret ? req.body.key_secret.trim() : req.body.key_secret;

  // Validate reseller ID format
  const uuidRegex =
    /^[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}$/i;
  if (!reseller_id || !uuidRegex.test(reseller_id)) {
    return res.status(400).json({
      success: false,
      message: "Invalid reseller ID",
    });
  }

  // Validate Razorpay keys if they are being updated
  if (key_id && key_secret) {
    try {
      // Test the credentials by making a lightweight API call
      const { default: Razorpay } = await import("razorpay");
      const rzpTest = new Razorpay({ key_id, key_secret });
      // Fetch a single plan to verify authentication works
      await rzpTest.plans.all({ count: 1 });
    } catch (error) {
      console.error("Razorpay API credential validation failed:", error);
      const errMsg = error.error?.description || error.message || "Unknown error";
      return res.status(400).json({
        success: false,
        message: errMsg === "Authentication failed" 
          ? "Invalid Razorpay Key ID or Key Secret. Please check your credentials." 
          : `Razorpay validation failed: ${errMsg}`
      });
    }
  }

  const { getHasuraClient } = await import("../config/hasura.client.js");
  const client = getHasuraClient();

  try {
    // Check if config exists
    const checkQuery = `
      query CheckRazorpayConfig($reseller_id: uuid!) {
        mst_razorpay_config(where: { reseller_id: { _eq: $reseller_id } }, limit: 1) {
          id
        }
      }
    `;

    const existingConfig = await client.client.request(checkQuery, {
      reseller_id,
    });

    let mutation;
    let variables;

    if (
      existingConfig.mst_razorpay_config &&
      existingConfig.mst_razorpay_config.length > 0
    ) {
      // Update existing config - build _set object conditionally to avoid null values
      const setFields = {
        is_active: true,
      };

      if (key_id !== undefined && key_id !== null && key_id !== "") {
        setFields.key_id = key_id;
      }

      if (
        key_secret !== undefined &&
        key_secret !== null &&
        key_secret !== ""
      ) {
        setFields.key_secret = key_secret;
      }

      if (
        webhook_secret !== undefined &&
        webhook_secret !== null &&
        webhook_secret !== ""
      ) {
        setFields.webhook_secret = webhook_secret;
      }

      // Build mutation dynamically based on which fields are present
      const setFieldsStr = Object.keys(setFields)
        .map((key) => `${key}: $${key}`)
        .join("\n              ");
      const variableDefs = ["$id: uuid!"];
      const variablesObj = { id: existingConfig.mst_razorpay_config[0].id };

      if (setFields.key_id !== undefined) {
        variableDefs.push("$key_id: String");
        variablesObj.key_id = setFields.key_id;
      }
      if (setFields.key_secret !== undefined) {
        variableDefs.push("$key_secret: String");
        variablesObj.key_secret = setFields.key_secret;
      }
      if (setFields.webhook_secret !== undefined) {
        variableDefs.push("$webhook_secret: String");
        variablesObj.webhook_secret = setFields.webhook_secret;
      }
      variableDefs.push("$is_active: Boolean");
      variablesObj.is_active = setFields.is_active;

      mutation = `
        mutation UpdateRazorpayConfig(
          ${variableDefs.join("\n          ")}
        ) {
          update_mst_razorpay_config_by_pk(
            pk_columns: { id: $id }
            _set: {
              ${setFieldsStr}
            }
          ) {
            id
            reseller_id
            key_id
            is_active
          }
        }
      `;

      variables = variablesObj;
    } else {
      // Create new config
      mutation = `
        mutation InsertRazorpayConfig(
          $reseller_id: uuid!
          $key_id: String
          $key_secret: String
          $webhook_secret: String
        ) {
          insert_mst_razorpay_config_one(object: {
            reseller_id: $reseller_id
            key_id: $key_id
            key_secret: $key_secret
            webhook_secret: $webhook_secret
            is_active: true
          }) {
            id
            reseller_id
            key_id
            is_active
          }
        }
      `;

      variables = {
        reseller_id,
        key_id: key_id || null,
        key_secret: key_secret || null,
        webhook_secret: webhook_secret || null,
      };
    }

    const result = await client.client.request(mutation, variables);
    const data =
      result.update_mst_razorpay_config_by_pk ||
      result.insert_mst_razorpay_config_one;

    // Generate webhook URL
    const baseUrl =
      process.env.API_BASE_URL || `${req.protocol}://${req.get("host")}`;
    const webhookUrl = WebhookService.generateWebhookUrl(reseller_id, baseUrl);

    const freshConfig = await WebhookService.getResellerRazorpayConfig(reseller_id);
    const key_secret_set = !!(
      freshConfig?.key_secret != null &&
      String(freshConfig.key_secret).trim() !== ""
    );

    return res.json({
      success: true,
      message: "Razorpay configuration saved successfully",
      data: {
        ...data,
        webhook_url: webhookUrl,
        key_secret: null,
        key_secret_set,
      },
    });
  } catch (error) {
    console.error("Error saving Razorpay config:", error);
    return res.status(500).json({
      success: false,
      message: error.message || "Failed to save Razorpay configuration",
    });
  }
});

