import { asyncHandler } from "../utils/asyncHandler.js";
import * as WebhookService from "../services/razorpay.webhook.service.js";

/**
 * @desc    Handle Razorpay webhook events from reseller accounts
 * @route   POST /api/razorpay/webhook/:resellerId
 * @access  Public (verified via signature)
 */
export const handleWebhook = asyncHandler(async (req, res) => {
  const { resellerId } = req.params;

  // Validate reseller ID format
  const uuidRegex =
    /^[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}$/i;
  if (!resellerId || !uuidRegex.test(resellerId)) {
    console.error("Invalid reseller ID in webhook URL:", resellerId);
    return res.status(400).json({
      success: false,
      message: "Invalid reseller ID",
    });
  }

  // Use the preserved raw body for signature verification.
  // req.rawBodyBuffer (Buffer) is preferred — byte-exact for HMAC. Fallback to req.rawBody (string).
  // Using JSON.stringify(req.body) is WRONG — it does not reproduce the original byte sequence.
  const rawBodyForVerify = req.rawBodyBuffer ?? req.rawBody;
  const signature = req.headers["x-razorpay-signature"];

  console.log(`[Webhook] Received for reseller=${resellerId}, hasRawBody=${!!rawBodyForVerify}, rawBodyLen=${rawBodyForVerify?.length ?? rawBodyForVerify?.byteLength}, hasSignature=${!!signature}`);
  console.log(`[Webhook] req._body=${req._body}, content-type=${req.headers["content-type"]}`);

  if (!rawBodyForVerify) {
    console.error(
      "[Webhook] rawBody is missing — req.rawBody was not set by middleware. Check index.js body capture middleware."
    );
    return res.status(400).json({
      success: false,
      message: "Webhook request body could not be read",
    });
  }

  // Parse the webhook payload first so we can extract notes.reseller_id
  // for config/signature lookup when the URL reseller has no config.
  let payload;
  try {
    payload = typeof req.body === "string" ? JSON.parse(req.body) : req.body;
  } catch (error) {
    console.error("Failed to parse webhook payload:", error);
    return res.status(400).json({
      success: false,
      message: "Invalid JSON payload",
    });
  }

  // Razorpay sends unique event id in header; JSON body may omit event_id.
  const hdrEventIdRaw =
    req.headers["x-razorpay-event-id"] ||
    req.headers["X-Razorpay-Event-Id"] ||
    req.headers["X-RAZORPAY-EVENT-ID"];
  const hdrEventId =
    hdrEventIdRaw != null && String(hdrEventIdRaw).trim() !== ""
      ? String(hdrEventIdRaw).trim()
      : null;
  if (!payload.event_id && hdrEventId) {
    payload.event_id = hdrEventId;
  }
  if (!payload.id && hdrEventId) {
    payload.id = hdrEventId;
  }

  // Extract payment entity for logging (declared here so it's available throughout the handler)
  const paymentEntity = payload.payload?.payment?.entity;

  // Get reseller's Razorpay config for webhook secret.
  // The webhook URL reseller_id is used for config lookup — signature verification
  // only runs if that specific reseller has a webhook_secret saved.
  // When the URL reseller has no config (e.g. a parent/platform account forwarding
  // events), we skip verification and rely on notes.reseller_id for processing.
  const config = await WebhookService.getResellerRazorpayConfig(resellerId);

  if (!config) {
    console.warn(`[Webhook] No Razorpay config for URL reseller=${resellerId} — skipping signature verification`);
  }

  if (process.env.REQUIRE_WEBHOOK_SECRET === "true") {
    const secretOk = config?.webhook_secret && String(config.webhook_secret).trim() !== "";
    if (!secretOk) {
      console.error(
        `[Webhook] FORBIDDEN: REQUIRE_WEBHOOK_SECRET=true but webhook_secret is missing for reseller=${resellerId}`,
      );
      return res.status(403).json({
        success: false,
        message:
          "Webhook not configured: add webhook_secret in Razorpay dashboard and save it in reseller Razorpay settings.",
      });
    }
  }

  // Verify webhook signature only when the URL reseller has a webhook_secret saved.
  // Do NOT try to verify with a different reseller's secret — the signature is always
  // generated by the Razorpay account that owns the webhook registration.
  if (config?.webhook_secret) {
    console.log(`[Webhook] Verifying signature for reseller=${resellerId}`);
    const isValid = WebhookService.verifyWebhookSignature(
      rawBodyForVerify,
      signature,
      config.webhook_secret
    );

    if (!isValid) {
      console.error(
        `Webhook signature verification failed for reseller: ${resellerId}. ` +
        `Ensure webhook_secret in mst_razorpay_config matches the secret from Razorpay Dashboard → Settings → Webhooks for this webhook URL.`
      );
      return res.status(401).json({
        success: false,
        message: "Invalid webhook signature",
      });
    }
    console.log(`[Webhook] Signature valid for reseller=${resellerId}`);
  } else {
    console.warn(`[Webhook] No webhook_secret configured for reseller=${resellerId} — skipping signature check`);
  }

  const event = payload.event;

  console.log(
    `[Webhook] Event: ${event} | reseller: ${resellerId} | payment_id: ${paymentEntity?.id} | amount_paise: ${paymentEntity?.amount} | email: ${paymentEntity?.email} | notes: ${JSON.stringify(paymentEntity?.notes)}`
  );
  console.log("[Webhook] Full payload:", JSON.stringify(payload, null, 2));

  let result;

  try {
    switch (event) {
      case "payment.authorized":
        result = await WebhookService.processPaymentAuthorized(
          resellerId,
          payload
        );
        break;

      case "payment.captured":
        result = await WebhookService.processPaymentCaptured(
          resellerId,
          payload
        );
        break;

      case "payment.failed":
        result = await WebhookService.processPaymentFailed(resellerId, payload);
        break;

      case "refund.created":
      case "refund.processed":
        result = await WebhookService.processRefundCreated(resellerId, payload);
        break;

      case "order.paid": {
        // CRITICAL: Razorpay sends order.paid + payment.captured + payment_link.paid for payment links.
        // Skip order.paid entirely when a transaction already exists — payment.captured is the
        // single handler for VN creation. Prevents race where both update the same pending txn.
        const orderPaymentId = payload.payload?.payment?.entity?.id;
        const orderId = payload.payload?.order?.entity?.id;
        if (orderPaymentId || orderId) {
          const existing = await WebhookService.transactionExists(
            orderPaymentId,
            orderId
          );
          if (existing) {
            console.log(
              `[Webhook] order.paid: Transaction already exists for payment ${orderPaymentId} ` +
                `(txn=${existing.id}) — skipping (payment.captured handles it)`
            );
            result = {
              success: true,
              data: existing,
              message: "Payment already processed (payment.captured handles it)",
            };
            break;
          }
        }
        result = await WebhookService.processOrderPaid(resellerId, payload);
        break;
      }

      case "subscription.charged":
        result = await WebhookService.processSubscriptionCharged(
          resellerId,
          payload
        );
        break;

      case "payment_link.paid": {
        // CRITICAL: Razorpay sends BOTH payment.captured AND payment_link.paid for the same
        // payment when using payment links. They have different event IDs, so both would be
        // processed and could trigger duplicate VN creation. Skip payment_link.paid entirely
        // if a transaction with this payment_id already exists (payment.captured handles it).
        const paymentEntity = payload.payload?.payment?.entity;
        const plEntity = payload.payload?.payment_link?.entity;
        const payments = Array.isArray(plEntity?.payments) ? plEntity.payments : [];
        const capturedPayment = payments.find((p) => p?.status === "captured") || payments[0];
        const paymentIdFromPl = capturedPayment?.id ?? capturedPayment?.payment_id ?? capturedPayment?.paymentId;
        const paymentId = paymentEntity?.id ?? paymentIdFromPl;
        const orderId = payload.payload?.order?.entity?.id ?? capturedPayment?.order_id;

        if (paymentId || orderId) {
          const existing = await WebhookService.transactionExists(paymentId, orderId);
          if (existing) {
            console.log(
              `[Webhook] payment_link.paid: Transaction already exists for payment ${paymentId} ` +
                `(txn=${existing.id}, vn_id=${existing.virtual_number_id}) — skipping to prevent duplicate VN (payment.captured handles it)`
            );
            result = {
              success: true,
              data: existing,
              message: "Payment already processed (payment.captured handles payment links)",
            };
            break;
          }
        }
        // No DB row matched yet: do NOT run processPaymentCaptured here.
        // Razorpay emits payment_link.paid and payment.captured for the same payment (different
        // event ids). Running fulfillment twice causes duplicate wallet debits. payment.captured
        // is the authoritative handler (Razorpay: idempotent, at-least-once delivery).
        console.log(
          `[Webhook] payment_link.paid: fulfillment deferred to payment.captured (pay=${paymentId || "n/a"})`,
        );
        result = {
          success: true,
          message:
            "payment_link.paid acknowledged; fulfillment runs on payment.captured only",
        };
        break;
      }

      case "subscription.completed":
      case "subscription.halted":
      case "subscription.cancelled":
        // Log subscription status changes but don't create new transactions
        console.log(
          `Subscription event ${event} received for reseller ${resellerId}`
        );
        result = {
          success: true,
          message: `Subscription event ${event} logged`,
        };
        break;

      default:
        // Log unknown events but acknowledge receipt
        console.log(
          `Unknown webhook event ${event} received for reseller ${resellerId}`
        );
        result = { success: true, message: `Event ${event} acknowledged` };
    }

    if (result.success || result.idempotentNoop) {
      console.log(
        `Webhook processed successfully: ${event} for reseller ${resellerId}`
      );
      return res.status(200).json({
        success: true,
        message: `Webhook processed: ${event}`,
        data: result.data,
      });
    } else {
      console.error(`Webhook processing failed: ${result.message}`);
      // Still return 200 to prevent Razorpay retries for business logic errors
      return res.status(200).json({
        success: false,
        message: result.message,
      });
    }
  } catch (error) {
    console.error("Error processing webhook:", error);
    // Return 200 to prevent Razorpay retries
    return res.status(200).json({
      success: false,
      message: "Webhook received but processing failed",
    });
  }
});

/**
 * @desc    Get all transactions for super admin dashboard
 * @route   GET /api/razorpay/transactions
 * @access  Private (Super Admin only)
 */
export const getAllTransactions = asyncHandler(async (req, res) => {
  const { limit, offset, status, reseller_id, start_date, end_date } =
    req.query;

  // Helper to clean query params - filter out undefined, empty strings, and literal "undefined"
  const cleanParam = (val) =>
    val && val !== "" && val !== "undefined" ? val : undefined;

  try {
    const result = await WebhookService.getAllTransactions({
      limit: limit ? parseInt(limit) : 100,
      offset: offset ? parseInt(offset) : 0,
      status: cleanParam(status),
      resellerId: cleanParam(reseller_id),
      startDate: cleanParam(start_date),
      endDate: cleanParam(end_date),
    });

    if (result.success) {
      return res.json({
        success: true,
        data: result.data,
      });
    } else {
      return res.status(400).json({
        success: false,
        message: result.message,
      });
    }
  } catch (error) {
    return res.status(500).json({
      success: false,
      message: error.message || "Failed to fetch transactions",
    });
  }
});

